#!/usr/bin/env python3
"""Manage isolated local AutoMem Docker stacks for matrix evals.

This writes a tiny compose override with alternate host ports, then shells out
to the sibling automem repo's docker-compose.yml using a unique Compose project
name. Separate project names mean separate Docker volumes.

Examples:
  python3 scripts/matrix_stack.py render --label candidate --api-port 8011
  python3 scripts/matrix_stack.py up --label candidate --api-port 8011
  python3 scripts/matrix_stack.py down --label candidate --api-port 8011
"""

from __future__ import annotations

import argparse
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_AUTOMEM_DIR = HERE.parent / "automem"
DEFAULT_OUTPUT_DIR = HERE / "data" / "matrix_stacks"


def slugify_label(label: str) -> str:
    slug = "".join(ch.lower() if ch.isalnum() else "-" for ch in label.strip())
    slug = "-".join(part for part in slug.split("-") if part)
    if not slug:
        raise ValueError("label must contain at least one alphanumeric character")
    return slug


def project_name(label: str) -> str:
    return f"automem_eval_{slugify_label(label).replace('-', '_')}"


def default_ports(api_port: int) -> dict[str, int]:
    offset = api_port - 8001
    return {
        "api": api_port,
        "falkor": 6379 + offset,
        "falkor_ui": 3000 + offset,
        "qdrant": 6333 + offset,
    }


def render_override(ports: dict[str, int]) -> str:
    return f"""# Generated by automem-evals/scripts/matrix_stack.py.
services:
  falkordb:
    ports: !override
      - "{ports['falkor']}:6379"
      - "{ports['falkor_ui']}:3000"

  qdrant:
    ports: !override
      - "{ports['qdrant']}:6333"

  flask-api:
    ports: !override
      - "{ports['api']}:8001"
    environment:
      PORT: 8001
      FALKORDB_HOST: falkordb
      FALKORDB_PORT: 6379
      QDRANT_URL: http://qdrant:6333
"""


def override_path(output_dir: pathlib.Path, label: str, api_port: int) -> pathlib.Path:
    return output_dir / f"{slugify_label(label)}-{api_port}.override.yml"


def compose_command(
    action: str,
    automem_dir: pathlib.Path,
    override_file: pathlib.Path,
    label: str,
) -> list[str]:
    base = [
        "docker",
        "compose",
        "-p",
        project_name(label),
        "-f",
        str(automem_dir / "docker-compose.yml"),
        "-f",
        str(override_file),
    ]
    if action == "up":
        return base + ["up", "-d"]
    if action == "down":
        return base + ["down"]
    raise ValueError(f"unsupported compose action: {action}")


def write_override(path: pathlib.Path, ports: dict[str, int]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_override(ports))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("action", choices=["render", "up", "down"])
    parser.add_argument("--label", required=True)
    parser.add_argument("--api-port", type=int, required=True)
    parser.add_argument("--falkor-port", type=int, default=None)
    parser.add_argument("--falkor-ui-port", type=int, default=None)
    parser.add_argument("--qdrant-port", type=int, default=None)
    parser.add_argument("--automem-dir", type=pathlib.Path, default=DEFAULT_AUTOMEM_DIR)
    parser.add_argument("--output-dir", type=pathlib.Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)

    ports = default_ports(args.api_port)
    if args.falkor_port is not None:
        ports["falkor"] = args.falkor_port
    if args.falkor_ui_port is not None:
        ports["falkor_ui"] = args.falkor_ui_port
    if args.qdrant_port is not None:
        ports["qdrant"] = args.qdrant_port

    path = override_path(args.output_dir, args.label, args.api_port)
    write_override(path, ports)
    print(f"override: {path}")
    print(f"endpoint: http://localhost:{ports['api']}")
    print(f"project:  {project_name(args.label)}")

    if args.action == "render":
        return 0

    cmd = compose_command(args.action, args.automem_dir, path, args.label)
    print("command:  " + " ".join(cmd))
    if args.dry_run:
        return 0
    subprocess.run(cmd, check=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
