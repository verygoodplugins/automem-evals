import gzip
import json
import sys
import tarfile
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import build_metadata_probe_scenario as builder


def write_snapshot(root: Path, memories: list[dict]) -> None:
    falkor = root / "falkordb"
    qdrant = root / "qdrant"
    falkor.mkdir(parents=True)
    qdrant.mkdir(parents=True)
    nodes = []
    points = []
    for idx, memory in enumerate(memories, start=1):
        props = {
            "id": memory["id"],
            "content": memory.get("content", ""),
            "tags": memory.get("tags", []),
            "metadata": json.dumps(memory.get("metadata", {})),
        }
        nodes.append({"id": idx, "labels": ["Memory"], "properties": props})
        points.append({"id": memory["id"], "vector": [0.1, 0.2], "payload": props})
    with gzip.open(falkor / "falkordb_20260609_000000.json.gz", "wt", encoding="utf-8") as handle:
        json.dump({"nodes": nodes, "relationships": [], "stats": {"node_count": len(nodes)}}, handle)
    with gzip.open(qdrant / "qdrant_20260609_000000.json.gz", "wt", encoding="utf-8") as handle:
        json.dump({"points": points, "stats": {"points_count": len(points), "vector_size": 2}}, handle)


class ProbeBuilderTests(unittest.TestCase):
    def test_builds_probe_rows_only_for_hidden_metadata_values(self):
        memories = [
            {
                "id": "m-hidden",
                "content": "Recall quality note.",
                "tags": ["automem-evals"],
                "metadata": {"source_agent": "hub-developer"},
            },
            {
                "id": "m-visible-content",
                "content": "This was generated by hub developer.",
                "tags": [],
                "metadata": {"source_agent": "hub-developer"},
            },
            {
                "id": "m-visible-tag",
                "content": "Recall quality note.",
                "tags": ["metadata-source-agent-hub-developer"],
                "metadata": {"source_agent": "hub-developer"},
            },
        ]

        rows = builder.build_probe_rows(memories, max_scenarios=20)

        self.assertEqual(len(rows), 1)
        row = rows[0]
        self.assertEqual(row["expected_ids"], ["m-hidden"])
        self.assertEqual(row["expected_field"], "source_agent")
        self.assertEqual(row["expected_value"], "hub-developer")
        self.assertEqual(row["query"], "memories with source agent hub developer")
        self.assertEqual(row["params"], {"limit": 10})

    def test_probe_ids_remain_unique_when_values_share_slug(self):
        rows = builder.build_probe_rows(
            [
                {
                    "id": "m-space",
                    "content": "Recall quality note.",
                    "tags": [],
                    "metadata": {"source": "user correction"},
                },
                {
                    "id": "m-underscore",
                    "content": "Recall quality note.",
                    "tags": [],
                    "metadata": {"source": "user_correction"},
                },
            ],
            max_scenarios=20,
        )

        ids = [row["id"] for row in rows]
        self.assertEqual(
            ids,
            ["MD-SOURCE-USER-CORRECTION", "MD-SOURCE-USER-CORRECTION-2"],
        )
        self.assertEqual(len(ids), len(set(ids)))

    def test_loads_restore_compatible_snapshot_directory(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            write_snapshot(
                root,
                [
                    {
                        "id": "m1",
                        "content": "Local evaluation note.",
                        "tags": ["automem-evals"],
                        "metadata": {"provider": "voyage"},
                    }
                ],
            )

            memories = builder.load_snapshot_memories(root)

        self.assertEqual(len(memories), 1)
        self.assertEqual(memories[0]["id"], "m1")
        self.assertEqual(memories[0]["metadata"], {"provider": "voyage"})

    def test_loads_restore_compatible_snapshot_tarball(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            snapshot_dir = root / "snapshot"
            write_snapshot(
                snapshot_dir,
                [
                    {
                        "id": "m1",
                        "content": "Local evaluation note.",
                        "tags": ["automem-evals"],
                        "metadata": {"provider": "voyage"},
                    }
                ],
            )
            tar_path = root / "snapshot.tar.gz"
            with tarfile.open(tar_path, "w:gz") as archive:
                archive.add(snapshot_dir / "falkordb", arcname="falkordb")
                archive.add(snapshot_dir / "qdrant", arcname="qdrant")

            memories = builder.load_snapshot_memories(tar_path)

        self.assertEqual(len(memories), 1)
        self.assertEqual(memories[0]["metadata"], {"provider": "voyage"})

    def test_build_scenario_includes_content_warmups(self):
        scenario = builder.build_scenario(
            [
                {
                    "id": "m1",
                    "content": "Vector readiness should use ordinary content words.",
                    "tags": [],
                    "metadata": {"provider": "voyage"},
                }
            ],
            warmup_count=1,
        )

        self.assertEqual(len(scenario["warmup_queries"]), 1)
        self.assertEqual(scenario["warmup_queries"][0]["expected_ids"], ["m1"])
        self.assertIn("vector readiness", scenario["warmup_queries"][0]["query"])


if __name__ == "__main__":
    unittest.main()
